USE ridetrack;
INSERT INTO trips(route_id,bus_id,depart_date,depart_time)
SELECT x.r,x.b,DATE_ADD(CURDATE(),INTERVAL d.n DAY),x.tm FROM
 (SELECT 1 r,1 b,'08:00' tm UNION SELECT 1,3,'22:00' UNION SELECT 2,1,'09:30' UNION SELECT 3,2,'07:15' UNION SELECT 4,3,'20:00') x
 JOIN (SELECT 0 n UNION SELECT 1 UNION SELECT 2 UNION SELECT 3 UNION SELECT 4 UNION SELECT 5 UNION SELECT 6) d;
